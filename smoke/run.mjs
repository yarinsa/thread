import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const page = await browser.newPage();
page.on('console', (m) => console.log('console:', m.text()));
page.on('pageerror', (e) => console.log('pageerror:', e.message));
await page.goto('http://localhost:4848/');
const host = page.locator('[data-review-overlay]');
await host.locator('button', { hasText: 'Comment' }).click();
await page.click('#save');
await host.locator('textarea').fill('Label should say Save changes');
await host.locator('button.primary').click();
await host.locator('.pin').waitFor();
await host.locator('textarea').fill('Agreed, fixing');
await host.locator('button.primary').click();
await page.waitForFunction(() => document.querySelector('[data-review-overlay]').shadowRoot.querySelectorAll('.comment').length === 2);
await page.screenshot({ path: 'smoke/after-reply.png' });
await host.getByRole('button', { name: 'Resolve', exact: true }).click();
await page.waitForFunction(() => document.querySelector('[data-review-overlay]').shadowRoot.querySelectorAll('.pin').length === 0);
await page.reload();
await host.locator('button', { hasText: 'Show resolved' }).click();
const pins = await host.locator('.pin').count();
const threads = await (await fetch('http://localhost:4747/threads?host=localhost:4848&project=smoke&branch=main&route=/')).json();
console.log(JSON.stringify({ pins, threads: threads.length, comments: threads[0]?.comments.length, resolved: threads[0]?.resolved, selector: threads[0]?.anchor.selector }));
await browser.close();
